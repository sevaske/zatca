<?php

namespace Sevaske\Zatca\Onboarding;

use LogicException;
use RuntimeException;
use Saleh7\Zatca\CertificateBuilder;
use Saleh7\Zatca\Exceptions\CertificateBuilderException;
use Sevaske\Zatca\Exceptions\ZatcaConfigurationException;
use Sevaske\Zatca\Invoice\InvoiceChain;
use Sevaske\Zatca\Invoice\SigningCredentials;
use Sevaske\Zatca\Models\EgsUnit;
use Sevaske\Zatca\Zatca;
use Sevaske\ZatcaApi\Credentials\ComplianceCsid;
use Sevaske\ZatcaApi\Environment;
use Sevaske\ZatcaApi\Response\ComplianceCheckResult;

/**
 * Onboarding of an EGS unit, step by step: private key and CSR, compliance CSID, compliance checks, production
 * CSID. Every step saves its result on the unit, so an interrupted onboarding continues where it stopped.
 *
 * `php artisan zatca:onboard` runs all the steps.
 *
 * @phpstan-type CsrOptions array{common_name: string, organization_name: string, organizational_unit: string, solution: string, model: string, serial: string, address: string, business_category: string, country?: string}
 */
class Onboarding
{
    public function __construct(protected Zatca $zatca) {}

    /**
     * Generate the private key and the CSR. The options are kept for renewals.
     *
     * @param  CsrOptions  $options  `serial` must be unique per unit; `organizational_unit` is the branch name
     *                               (for VAT groups: the TIN of the member)
     *
     * @throws CertificateBuilderException for invalid options
     */
    public function generateCsr(EgsUnit $unit, array $options): EgsUnit
    {
        if ($unit->isOnboarded()) {
            throw new LogicException("EGS unit \"{$unit->key}\" is onboarded already. Renew its CSID instead.");
        }

        $builder = $this->csr($unit, $options);

        $unit->forceFill([
            'csr_options' => $options,
            'csr' => $builder->getCsr(),
            'private_key' => $builder->getPrivateKey(),
            'compliance_csid' => null,
        ])->save();

        return $unit;
    }

    /**
     * Exchange the CSR and a one-time password from the Fatoora portal for a compliance CSID.
     *
     * @param  string  $otp  valid for one hour; in the sandbox it is 123345
     */
    public function requestComplianceCsid(EgsUnit $unit, string $otp): EgsUnit
    {
        $csid = $this->zatca->client($unit->environment)->onboarding()
            ->requestComplianceCsid($unit->csr ?? throw ZatcaConfigurationException::missing('CSR', $unit->key), $otp)
            ->toComplianceCsid();

        $unit->forceFill(['compliance_csid' => $csid->toArray()])->save();

        return $unit;
    }

    /**
     * Sign a sample of every document type the unit declared and check it with ZATCA.
     *
     * Samples do not belong to the unit's chain: they form a chain of their own and are not stored.
     *
     * @param  array<string, array<string, mixed>>|null  $samples  invoice data by label; generated by default
     * @return array<string, ComplianceCheckResult> by label
     */
    public function runComplianceChecks(EgsUnit $unit, ?array $samples = null): array
    {
        return $this->check($unit, $unit->complianceCredentials(), $samples ?? ComplianceSamples::for($unit));
    }

    /**
     * Exchange the compliance CSID for a production CSID, after the compliance checks have passed.
     */
    public function requestProductionCsid(EgsUnit $unit): EgsUnit
    {
        $csid = $this->zatca->client($unit->environment)->onboarding()
            ->requestProductionCsid($unit->complianceCsid())
            ->toProductionCsid();

        $unit->forceFill(['production_csid' => $csid->toArray()])->save();

        return $unit;
    }

    /**
     * Renew the production CSID with a new private key and CSR. The unit keeps its chain.
     *
     * When ZATCA asks for compliance checks first (HTTP 428), they are run with generated samples.
     *
     * @param  CsrOptions|null  $options  defaults to the options of the previous CSR
     */
    public function renew(EgsUnit $unit, string $otp, ?array $options = null): EgsUnit
    {
        $options ??= $unit->csr_options ?? throw ZatcaConfigurationException::missing('CSR options', $unit->key);
        $builder = $this->csr($unit, $options);
        $client = $this->zatca->client($unit->environment)->onboarding();

        $response = $client->renewProductionCsid($unit->productionCsid(), $builder->getCsr(), $otp);

        // HTTP 428 / NOT_COMPLIANT: ZATCA issued a compliance CSID for the new key instead
        if ($response->isNotCompliant() || $response->getHttpStatusCode() === 428) {
            $compliance = new SigningCredentials($response->toComplianceCsid(), $builder->getPrivateKey());
            $failed = array_filter($this->check($unit, $compliance, ComplianceSamples::for($unit)), fn ($result) => ! $result->isPassed());

            if ($failed !== []) {
                throw new RuntimeException('Compliance checks failed during renewal: '.implode(', ', array_keys($failed)).'.');
            }

            $response = $client->requestProductionCsid($response->toComplianceCsid());
        }

        // the key and the CSID change together: signing with a mismatched pair is rejected
        $unit->forceFill([
            'csr_options' => $options,
            'csr' => $builder->getCsr(),
            'private_key' => $builder->getPrivateKey(),
            'production_csid' => $response->toProductionCsid()->toArray(),
        ])->save();

        return $unit;
    }

    /**
     * @param  array<string, array<string, mixed>>  $samples
     * @return array<string, ComplianceCheckResult>
     */
    protected function check(EgsUnit $unit, SigningCredentials $credentials, array $samples): array
    {
        $invoices = $this->zatca->invoices($unit->environment);
        $csid = $credentials->csid instanceof ComplianceCsid
            ? $credentials->csid
            : throw new LogicException('Compliance checks need a compliance CSID.');

        $results = [];
        $icv = 0;
        $pih = InvoiceChain::INITIAL_HASH;

        foreach ($samples as $label => $data) {
            $document = $invoices->sign(InvoiceChain::link($invoices->invoice($data), ++$icv, $pih), $credentials);
            $results[$label] = $invoices->check($document, $csid);
            $pih = $document->hash;
        }

        return $results;
    }

    /**
     * @param  CsrOptions  $options
     */
    protected function csr(EgsUnit $unit, array $options): CertificateBuilder
    {
        return (new CertificateBuilder)
            ->setOrganizationIdentifier($unit->vat_number)
            ->setSerialNumber($options['solution'], $options['model'], $options['serial'])
            ->setCommonName($options['common_name'])
            ->setCountryName($options['country'] ?? 'SA')
            ->setOrganizationName($options['organization_name'])
            ->setOrganizationalUnitName($options['organizational_unit'])
            ->setAddress($options['address'])
            ->setInvoiceType((int) $unit->invoice_types)
            ->setBusinessCategory($options['business_category'])
            ->setProduction($unit->environment === Environment::PRODUCTION)
            ->generate();
    }
}
